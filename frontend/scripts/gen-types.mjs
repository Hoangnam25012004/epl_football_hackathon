// Generate src/lib/contracts/index.ts from the JSON Schemas the backend exports
// (`pundit schema` → packages/schemas). Never edit the output by hand (docs/day4-design.md 4.2).
//
//   node scripts/gen-types.mjs           write the file
//   node scripts/gen-types.mjs --check   exit 1 when the committed file is out of date (CI)

import { readFileSync, writeFileSync, mkdirSync, existsSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { compile } from "json-schema-to-typescript";

const here = dirname(fileURLToPath(import.meta.url));
const schemaDir = join(here, "..", "..", "packages", "schemas");
const outFile = join(here, "..", "src", "lib", "contracts", "index.ts");

// Responses first (serialization mode): when a request schema defines the same model in
// validation mode, the response version is kept.
const SCHEMAS = [
  "ws_payloads",
  "match_view",
  "studio_item_detail",
  "timeline",
  "stats_panel",
  "events_page",
  "scenario_info",
  "player_brief",
  "health",
  "on_air",
  "claim_result",
  "create_match",
  "on_air_command",
  "claim_request",
  "speech_voice", // Day 5: the voices of the fan player
  "recognition_result", // Day 5: speech to text of a spoken claim
  "agent_ops_message", // Day 7: Agent Ops (hello with the snapshot, batches of events)
  "chaos_command", // Day 7: break the model of a private session
];

const BANNER = `/* eslint-disable */
// DO NOT EDIT: generated by scripts/gen-types.mjs from packages/schemas (pundit schema).`;

function stripTitles(node, keepTitle) {
  // pydantic puts a title on every property; json-schema-to-typescript would turn each one into
  // a named alias ("MatchId", "MatchId1"...). Only models ($defs and roots) keep their name.
  if (Array.isArray(node)) return node.map((item) => stripTitles(item, false));
  if (node === null || typeof node !== "object") return node;
  const copy = {};
  for (const [key, value] of Object.entries(node)) {
    if (key === "title" && !keepTitle) continue;
    if (key === "$defs") {
      copy.$defs = Object.fromEntries(
        Object.entries(value).map(([name, def]) => [name, stripTitles(def, true)]),
      );
    } else if (key === "properties") {
      copy.properties = Object.fromEntries(
        Object.entries(value).map(([name, prop]) => [name, stripTitles(prop, false)]),
      );
    } else {
      copy[key] = stripTitles(value, false);
    }
  }
  return copy;
}

function sameJson(a, b) {
  return JSON.stringify(a) === JSON.stringify(b);
}

async function generate() {
  const defs = {};
  const roots = [];
  for (const name of SCHEMAS) {
    const raw = JSON.parse(readFileSync(join(schemaDir, `${name}.schema.json`), "utf8"));
    const schema = stripTitles(raw, true);
    const title = schema.title;
    if (!title) throw new Error(`${name}.schema.json has no title`);
    for (const [defName, def] of Object.entries(schema.$defs ?? {})) {
      if (!(defName in defs)) defs[defName] = def;
      else if (!sameJson(defs[defName], def) && process.env.DEBUG_GEN_TYPES) {
        console.warn(`keeping the first definition of ${defName} (from a response schema)`);
      }
    }
    const root = { ...schema };
    delete root.$defs;
    if (title in defs && !sameJson(defs[title], root)) {
      throw new Error(`two different schemas are both called ${title}`);
    }
    defs[title] = root;
    roots.push(title);
  }
  const wrapper = {
    title: "Contracts",
    type: "object",
    additionalProperties: false,
    properties: Object.fromEntries(roots.map((title) => [title, { $ref: `#/$defs/${title}` }])),
    required: roots,
    $defs: defs,
  };
  return compile(wrapper, "Contracts", {
    bannerComment: BANNER,
    additionalProperties: false,
    unreachableDefinitions: true,
    declareExternallyReferenced: true,
    style: { printWidth: 100, singleQuote: false, trailingComma: "all" },
  });
}

const check = process.argv.includes("--check");
const output = await generate();
if (check) {
  const current = existsSync(outFile) ? readFileSync(outFile, "utf8") : "";
  if (current.replace(/\r\n/g, "\n") !== output.replace(/\r\n/g, "\n")) {
    console.error("src/lib/contracts/index.ts is out of date: run `npm run gen:types`");
    process.exit(1);
  }
  console.log("contracts up to date");
} else {
  mkdirSync(dirname(outFile), { recursive: true });
  writeFileSync(outFile, output.replace(/\r\n/g, "\n"), "utf8");
  console.log(`wrote ${outFile}`);
}
